  const deliveryDescription =
    freeDelivery === null
      ? storeConfig.checkout.deliveryZones
          .map((zone) => `${zone.label}: ${formatMoney(zone.fee)}`)
          .join(" · ")
      : `Frete grátis em pedidos a partir de ${formatMoney(freeDelivery)}.`;
