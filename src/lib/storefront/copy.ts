export function heroSlideText(
  index: number,
  banner: {
    title: string | null;
    subtitle: string | null;
    ctaLabel: string | null;
    href: string | null;
  },
) {
  const preset = homepageHeroSlides[index];
  if (!preset) {
    return {
      title: banner.title ?? "",
      subtitle: banner.subtitle ?? "",
      ctaLabel: banner.ctaLabel ?? "Comprar agora",
      href: banner.href,
    };
  }
  return {
    title: preset.title,
    subtitle: preset.subtitle,
    ctaLabel: preset.ctaLabel,
    href: banner.href ?? preset.href,
  };
}

